use super::*;
use assay_runner_schema::{CapabilitySurface, CorrelationReport, ObservationHealth};
use flate2::{Compression, GzBuilder};
use serde_json::json;
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;

const RUN: &str = "synthetic_archive_verification";

fn fixture() -> Vec<u8> {
    fixture_with(|_| {})
}

fn fixture_with(change: impl FnOnce(&mut BTreeMap<&str, Vec<u8>>)) -> Vec<u8> {
    let mut files: BTreeMap<&str, Vec<u8>> = BTreeMap::from([
        ("events.ndjson", Vec::new()),
        ("layers/kernel.ndjson", Vec::new()),
        ("layers/policy.ndjson", Vec::new()),
        ("layers/sdk.ndjson", Vec::new()),
        (
            "capability-surface.json",
            serde_json::to_vec(&CapabilitySurface::new(RUN)).unwrap(),
        ),
        (
            "correlation-report.json",
            serde_json::to_vec(&CorrelationReport::clean(RUN)).unwrap(),
        ),
        (
            "observation-health.json",
            serde_json::to_vec(&ObservationHealth::new(RUN, "linux")).unwrap(),
        ),
    ]);
    change(&mut files);
    let entries: BTreeMap<_, _> = files
        .iter()
        .map(|(name, bytes)| {
            (
                *name,
                json!({"path": name, "bytes": bytes.len(),
                "sha256": format!("sha256:{}", hex::encode(Sha256::digest(bytes)))}),
            )
        })
        .collect();
    let manifest = serde_json::to_vec(&json!({
        "schema": "assay.runner.archive_manifest.v0", "run_id": RUN, "files": entries
    }))
    .unwrap();
    let encoder = GzBuilder::new()
        .mtime(0)
        .write(Vec::new(), Compression::fast());
    let mut tar = tar::Builder::new(encoder);
    for (name, bytes) in std::iter::once(("manifest.json", manifest)).chain(files) {
        let mut header = tar::Header::new_gnu();
        header.set_size(bytes.len() as u64);
        header.set_mode(0o644);
        header.set_cksum();
        tar.append_data(&mut header, name, bytes.as_slice())
            .unwrap();
    }
    tar.into_inner().unwrap().finish().unwrap()
}

#[test]
fn original_runner_archive_can_be_verified_without_rewriting_it() {
    // Catches a missing reader or dispatch that incorrectly uses the two-file bundle format.
    // Hashing the generated bytes selects the external expectation; acceptance is literal.
    let bytes = fixture();
    let digest = hex::encode(Sha256::digest(&bytes));
    let result = verify_runner_archive(bytes.as_slice(), &digest, RUN, VerifyLimits::default());
    assert!(
        result.is_ok(),
        "valid existing Runner format refused: {result:?}"
    );
}

fn verify(bytes: &[u8], digest: &str, run: &str, limits: VerifyLimits) -> Result<(), VerifyError> {
    verify_runner_archive(bytes, digest, run, limits)
}

#[test]
fn coherent_replacement_cannot_replace_the_external_expectation() {
    let original = fixture();
    let changed = fixture_with(|files| {
        files.insert("events.ndjson", b"{\"different\":true}\n".to_vec());
    });
    let digest = hex::encode(Sha256::digest(&original));
    let err = verify(&changed, &digest, RUN, VerifyLimits::default()).unwrap_err();
    assert_eq!(err.class, ErrorClass::Integrity);
}

#[test]
fn external_run_id_cannot_be_replaced_by_valid_metadata() {
    let bytes = fixture();
    let digest = hex::encode(Sha256::digest(&bytes));
    let err = verify(&bytes, &digest, "foreign_run", VerifyLimits::default()).unwrap_err();
    assert_eq!(err.code, ErrorCode::ContractRunIdMismatch);
}

#[test]
fn recomputed_hashes_do_not_admit_invalid_health() {
    let bytes = fixture_with(|files| {
        let mut health: serde_json::Value =
            serde_json::from_slice(&files["observation-health.json"]).unwrap();
        health["ringbuf_drops"] = json!(1);
        files.insert(
            "observation-health.json",
            serde_json::to_vec(&health).unwrap(),
        );
    });
    let digest = hex::encode(Sha256::digest(&bytes));
    let err = verify(&bytes, &digest, RUN, VerifyLimits::default()).unwrap_err();
    assert_eq!(err.code, ErrorCode::ContractInvalidEvent);
}

#[test]
fn recomputed_hashes_do_not_admit_duplicate_metadata_keys() {
    let bytes = fixture_with(|files| {
        let source = files.get_mut("observation-health.json").unwrap();
        source.splice(1..1, b"\"run_id\":\"foreign\",".iter().copied());
    });
    let digest = hex::encode(Sha256::digest(&bytes));
    let err = verify(&bytes, &digest, RUN, VerifyLimits::default()).unwrap_err();
    assert_eq!(err.code, ErrorCode::ContractInvalidJson);
}

