#[test]
fn manifest_schema_and_declared_path_are_checked() {
    for (field, value, code) in [
        ("schema", "unknown", ErrorCode::ContractSchemaVersion),
        ("path", "foreign.json", ErrorCode::ContractUnexpectedFile),
    ] {
        let mut entries = unpack(&fixture());
        let mut manifest: serde_json::Value = serde_json::from_slice(&entries[0].1).unwrap();
        if field == "schema" {
            manifest[field] = json!(value);
        } else {
            manifest["files"]["capability-surface.json"][field] = json!(value);
        }
        entries[0].1 = serde_json::to_vec(&manifest).unwrap();
        refuse_current(&pack(entries), code);
    }
}

