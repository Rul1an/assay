#[test]
fn complete_gzip_without_tar_terminator_is_refused() {
    use std::io::Write;
    let bytes = fixture();
    let mut decoded = Vec::new();
    flate2::read::GzDecoder::new(bytes.as_slice())
        .read_to_end(&mut decoded)
        .unwrap();
    let end = tar::Archive::new(decoded.as_slice())
        .entries()
        .unwrap()
        .map(|e| {
            let e = e.unwrap();
            e.raw_file_position() + e.size().div_ceil(512) * 512
        })
        .max()
        .unwrap() as usize;
    let mut gzip = GzBuilder::new()
        .mtime(0)
        .write(Vec::new(), Compression::fast());
    gzip.write_all(&decoded[..end]).unwrap();
    refuse_current(&gzip.finish().unwrap(), ErrorCode::IntegrityTar);
}

#[test]
fn oversized_source_stops_after_the_boundary_probe() {
    use std::cell::Cell;
    struct Counted<'a> {
        bytes: &'a [u8],
        returned: &'a Cell<usize>,
    }
    impl Read for Counted<'_> {
        fn read(&mut self, output: &mut [u8]) -> std::io::Result<usize> {
            let count = self.bytes.read(output)?;
            self.returned.set(self.returned.get() + count);
            Ok(count)
        }
    }
    let bytes = fixture();
    let returned = Cell::new(0);
    let reader = Counted {
        bytes: &bytes,
        returned: &returned,
    };
    let limits = VerifyLimits {
        max_bundle_bytes: 128,
        ..VerifyLimits::default()
    };
    let result = verify_runner_archive(reader, &hex::encode(Sha256::digest(&bytes)), RUN, limits);
    assert_eq!(result.unwrap_err().code, ErrorCode::LimitBundleBytes);
    assert_eq!(
        returned.get(),
        129,
        "only the limit plus one EOF probe may be read"
    );
}

#[test]
fn links_and_path_aliases_are_not_regular_members() {
    for link in [true, false] {
        let encoder = GzBuilder::new()
            .mtime(0)
            .write(Vec::new(), Compression::fast());
        let mut tar = tar::Builder::new(encoder);
        for (index, (name, bytes)) in unpack(&fixture()).into_iter().enumerate() {
            let mut header = tar::Header::new_gnu();
            header.set_size(bytes.len() as u64);
            header.set_mode(0o644);
            header.set_path(&name).unwrap();
            if index == 1 {
                if link {
                    header.set_entry_type(tar::EntryType::Symlink);
                    header.set_link_name("ignored-target").unwrap();
                } else {
                    let alias = format!("./{name}");
                    header.as_mut_bytes()[..100].fill(0);
                    header.as_mut_bytes()[..alias.len()].copy_from_slice(alias.as_bytes());
                }
            }
            header.set_cksum();
            tar.append(&header, bytes.as_slice()).unwrap();
        }
        let bytes = tar.into_inner().unwrap().finish().unwrap();
        refuse_current(
            &bytes,
            if link {
                ErrorCode::IntegrityTar
            } else {
                ErrorCode::ContractUnexpectedFile
            },
        );
    }
}

