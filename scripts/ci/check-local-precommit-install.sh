#!/usr/bin/env bash
# Read-only check that this checkout's git hooks are pre-commit's own, at the version CI installs.
#
# `pre-commit install` writes the interpreter it ran under (sys.executable) into each hook as
# INSTALL_PYTHON. When that interpreter disappears, for instance a `pipx run` cache that was
# cleaned up, the hook falls back without a word to whatever `pre-commit` is on PATH at push
# time: another version than CI, or none at all.
#
# For each hook where pre-commit installs it (the common git dir) this checks, without running it:
#   - git will run it: core.hooksPath is unset, and the file exists and is executable;
#   - its templated block is what the installer writes for this repository:
#     ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=<this hook>), and an
#     INSTALL_PYTHON that exists and reports the CI pin;
#   - everything outside that block is byte-for-byte the template that this interpreter's own
#     pre-commit ships (pre_commit/resources/hook-tmpl), read the way pre-commit reads it.
# Together: the hook dispatches to that interpreter's pre-commit, at the pin, for this config.
# Not claimed: how `#!/usr/bin/env bash` resolves, or what `hook-impl` then does.
# CI has no installed hooks, so this is a local check.
#
# Usage: bash scripts/ci/check-local-precommit-install.sh   (0 ok, 1 problems found, 2 usage)
set -euo pipefail

if [[ "$#" -ne 0 ]]; then
  echo "usage: check-local-precommit-install.sh (takes no arguments)" >&2
  exit 2
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
pin="$(bash "${ROOT}/scripts/ci/read-pre-commit-pin.sh")"
fix="fix: install pre-commit ${pin} in a fixed Assay environment (not \`pipx run\`), then run that environment's \`pre-commit install\`"
problems=0
problem() {
  echo "FAIL: $*"
  problems=$((problems + 1))
}
# The non-templated part of a hook: every line outside `# start templated` .. `# end templated`.
outside_block() {
  sed '/^# start templated$/,/^# end templated$/d'
}
# The hook template that interpreter $1's own pre-commit ships, read the way pre-commit's
# resource_text reads it. A failed read prints nothing, which never equals a hook.
shipped_template() {
  "$1" -c 'import importlib.resources as r, sys; sys.stdout.write(r.files("pre_commit.resources").joinpath("hook-tmpl").read_text())' 2>/dev/null
}

# pre-commit installs into the common dir's hooks/. git takes hooks from core.hooksPath whenever
# that key exists, an empty value included (git then looks in "./"), while pre-commit reads an
# empty value as unset and installs anyway. So any value refuses; only an absent key (rc 1) passes.
hooks_dir="$(git -C "${ROOT}" rev-parse --path-format=absolute --git-common-dir)/hooks"
hooks_path_rc=0
hooks_path="$(git -C "${ROOT}" config --get core.hooksPath)" || hooks_path_rc=$?
if [[ "${hooks_path_rc}" != 1 ]]; then
  problem "core.hooksPath is set (to '${hooks_path}'): git takes hooks from that setting, an empty value included, while pre-commit installs into ${hooks_dir}; unset it"
fi

for hook_type in pre-commit pre-push; do
  hook="${hooks_dir}/${hook_type}"
  if [[ ! -f "${hook}" ]]; then
    problem "${hook_type}: not installed (${hook}); ${fix}"
    continue
  fi
  if ! grep -qxF '# File generated by pre-commit: https://pre-commit.com' "${hook}"; then
    problem "${hook_type}: not generated by pre-commit (${hook})"
    continue
  fi
  if [[ ! -x "${hook}" ]]; then
    problem "${hook_type}: not executable (${hook}), so git skips it; ${fix}"
    continue
  fi
  # Every templated block in the file (sed takes them all), compared with exactly the four lines
  # the installer writes. Any other line, or a second block, can stop or redirect dispatch.
  block="$(sed -n '/^# start templated$/,/^# end templated$/p' "${hook}")"
  python_line="$(printf '%s\n' "${block}" | sed -n 2p)"
  args_line="$(printf '%s\n' "${block}" | sed -n 3p)"
  want_block="$(printf '%s\n' '# start templated' "INSTALL_PYTHON=${python_line#INSTALL_PYTHON=}" "${args_line}" '# end templated')"
  if [[ "${block}" != "${want_block}" ]]; then
    problem "${hook_type}: the templated block does not have the form pre-commit writes (${hook})"
    continue
  fi
  want_args="ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=${hook_type})"
  if [[ "${args_line}" != "${want_args}" ]]; then
    problem "${hook_type}: ARGS is not exactly '${want_args}' but '${args_line}' (${hook}); ${fix}"
    continue
  fi
  # pre-commit writes shlex.quote(sys.executable): bare, from shlex's safe characters only, or in
  # single quotes when it needs them. Anything else on the line is not the installer's.
  raw="${python_line#INSTALL_PYTHON=}"
  python="${raw}"
  if [[ "${raw}" == \'*\' ]]; then
    python="${raw#\'}"
    python="${python%\'}"
  elif [[ ! "${raw}" =~ ^[A-Za-z0-9_@%+=:,./-]+$ ]]; then
    python=""
  fi
  if [[ -z "${python}" || "${python}" == *"'"* ]]; then
    problem "${hook_type}: cannot read INSTALL_PYTHON ${raw} (${hook}); ${fix}"
    continue
  fi
  if [[ ! -x "${python}" ]]; then
    problem "${hook_type}: INSTALL_PYTHON ${python} is missing, so the hook falls back to whatever pre-commit is on PATH at push time; ${fix}"
    continue
  fi
  version="$("${python}" -mpre_commit --version 2>&1 || true)"
  if [[ "${version}" != "pre-commit ${pin}" ]]; then
    problem "${hook_type}: runs ${version:-nothing} through ${python}, CI pins ${pin}; ${fix}"
    continue
  fi
  if ! cmp -s <(outside_block < "${hook}") <(shipped_template "${python}" | outside_block); then
    problem "${hook_type}: differs from pre-commit ${pin}'s own hook template outside the templated block (${hook}); ${fix}"
    continue
  fi
  echo "ok: ${hook_type} is pre-commit ${pin}'s own template, executable, for .pre-commit-config.yaml, dispatching to ${python}"
done

if (( problems > 0 )); then
  echo "local pre-commit hooks: ${problems} problem(s)"
  exit 1
fi
echo "local pre-commit hooks: OK, both are pre-commit ${pin}'s own template and dispatch to their recorded interpreter"
