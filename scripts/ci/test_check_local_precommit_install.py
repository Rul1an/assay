#!/usr/bin/env python3
"""Fixture tests for check-local-precommit-install.sh, the read-only doctor for local git hooks.

Each test builds a throwaway git repository and writes the two hooks the way `pre-commit install`
writes them: its template, `shlex.quote(sys.executable)`, `shlex.join(args)`. INSTALL_PYTHON points
at a stub interpreter: the running Python with a fake `pre_commit` package on PYTHONPATH. The fake
package answers `--version`, carries its own `resources/hook-tmpl`, and records the argv of every
other call. That lets a test prove that a hook the doctor accepts really dispatches to the
recorded interpreter, and that the doctor takes the template from that interpreter, not from a
copy. Nothing real is installed: no pre-commit, no network, no write to this repository's hooks.
Global and system git config are cut off, so a developer's own `core.hooksPath` cannot leak in.

Every refusal is asserted by its own message, so a case stays red for the reason it names and
not because an earlier check happened to fail.
"""

import hashlib
import json
import os
import shlex
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCTOR = ROOT / "scripts/ci/check-local-precommit-install.sh"
READER = ROOT / "scripts/ci/read-pre-commit-pin.sh"
PIN = "4.4.0"
HOOK_TYPES = ("pre-commit", "pre-push")
MARKER = "# File generated by pre-commit: https://pre-commit.com\n"
CONFIG_ARG = "--config=.pre-commit-config.yaml"

# pre-commit's own hook-tmpl. The installer fills the templated block; the resource ships it as
# INSTALL_PYTHON='' and ARGS=(hook-impl).
TEMPLATE = (
    "#!/usr/bin/env bash\n"
    + MARKER
    + "# ID: 138fd403232d2ddd5efb44317e38bf03\n"
    "\n"
    "# start templated\n"
    "INSTALL_PYTHON=@PYTHON@\n"
    "ARGS=(@ARGS@)\n"
    "# end templated\n"
    "\n"
    'HERE="$(cd "$(dirname "$0")" && pwd)"\n'
    'ARGS+=(--hook-dir "$HERE" -- "$@")\n'
    "\n"
    'if [ -x "$INSTALL_PYTHON" ]; then\n'
    '    exec "$INSTALL_PYTHON" -mpre_commit "${ARGS[@]}"\n'
    "elif command -v pre-commit > /dev/null; then\n"
    '    exec pre-commit "${ARGS[@]}"\n'
    "else\n"
    "    echo '`pre-commit` not found.  Did you forget to activate your virtualenv?' 1>&2\n"
    "    exit 1\n"
    "fi\n"
)
RESOURCE_TEMPLATE = TEMPLATE.replace("@PYTHON@", "''").replace("@ARGS@", "hook-impl")

FAKE_MAIN = (
    "import json, os, sys\n"
    "if sys.argv[1:] == ['--version']:\n"
    "    print('pre-commit @VERSION@')\n"
    "    raise SystemExit(0)\n"
    "with open(os.environ['DISPATCH_RECORD'], 'a', encoding='utf-8') as stream:\n"
    "    stream.write(json.dumps({'via': os.environ.get('DISPATCH_VIA'), 'argv': sys.argv[1:]}) + '\\n')\n"
)


class Fixture:
    def __init__(self, base):
        self.base = Path(base)
        self.repo = self.base / "repo"
        (self.repo / "scripts/ci").mkdir(parents=True)
        (self.repo / ".github/workflows").mkdir(parents=True)
        shutil.copy2(DOCTOR, self.repo / "scripts/ci" / DOCTOR.name)
        shutil.copy2(READER, self.repo / "scripts/ci" / READER.name)
        (self.repo / ".github/workflows/kernel-matrix.yml").write_text(
            f"      - run: |\n          pip install pre-commit=={PIN}\n", encoding="utf-8"
        )
        self.record = self.base / "dispatch.jsonl"
        self.env = {
            "PATH": os.environ["PATH"],
            "HOME": str(self.base / "home"),
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CONFIG_NOSYSTEM": "1",
            "LC_ALL": "C",
            "PYTHONDONTWRITEBYTECODE": "1",
            "DISPATCH_RECORD": str(self.record),
        }
        self.git("init", "-q")
        self.hooks = self.repo / ".git/hooks"
        self.hooks.mkdir(exist_ok=True)

    def git(self, *args):
        subprocess.run(["git", *args], cwd=self.repo, env=self.env, check=True, capture_output=True)

    def stub_python(self, version, directory="bin", template=RESOURCE_TEMPLATE):
        """The running Python with a fake pre_commit package: a version, a template, a recorder."""
        folder = self.base / directory
        package = folder / "fakepkg/pre_commit"
        (package / "resources").mkdir(parents=True, exist_ok=True)
        (package / "__init__.py").write_text("")
        (package / "__main__.py").write_text(FAKE_MAIN.replace("@VERSION@", version))
        (package / "resources/__init__.py").write_text("")
        (package / "resources/hook-tmpl").write_text(template)
        stub = folder / "python"
        stub.write_text(
            "#!/bin/sh\n"
            f"DISPATCH_VIA={shlex.quote(str(stub))}; export DISPATCH_VIA\n"
            f"PYTHONPATH={shlex.quote(str(folder / 'fakepkg'))} exec {shlex.quote(sys.executable)} \"$@\"\n",
            encoding="utf-8",
        )
        stub.chmod(0o755)
        return stub

    def write_hook(self, hook_type, python, args=None):
        args = args or ["hook-impl", CONFIG_ARG, f"--hook-type={hook_type}"]
        hook = self.hooks / hook_type
        # Placeholders, not str.format: the template's own `${ARGS[@]}` holds braces.
        text = TEMPLATE.replace("@PYTHON@", shlex.quote(str(python))).replace("@ARGS@", shlex.join(args))
        hook.write_text(text, encoding="utf-8")
        hook.chmod(0o755)
        return hook

    def install(self, python):
        for hook_type in HOOK_TYPES:
            self.write_hook(hook_type, python)

    def run(self, *args, cwd=None):
        result = subprocess.run(
            ["bash", str(self.repo / "scripts/ci" / DOCTOR.name), *args],
            cwd=cwd or self.repo, env=self.env, capture_output=True, text=True, timeout=60,
        )
        return result.returncode, result.stdout + result.stderr

    def run_hook(self, hook_type, *args):
        # No pre-commit on this PATH: a hook that fell back to PATH would fail, not pass.
        env = dict(self.env, PATH="/usr/bin:/bin")
        return subprocess.run([str(self.hooks / hook_type), *args], cwd=self.repo, env=env,
                              capture_output=True, text=True, timeout=60)

    def dispatched(self):
        if not self.record.exists():
            return []
        return [json.loads(line) for line in self.record.read_text().splitlines()]

    def snapshot(self):
        digest = hashlib.sha256()
        for path in sorted(self.hooks.rglob("*")):
            stat = path.stat()
            digest.update(f"{path.relative_to(self.hooks)}|{stat.st_mode}|{stat.st_mtime_ns}|".encode())
            if path.is_file():
                digest.update(path.read_bytes())
        return digest.hexdigest()


def git_runs_common_hooks_with(env, base, hooks_path):
    """Measure with a real commit whether git runs .git/hooks while core.hooksPath is `hooks_path`."""
    repo, marker = base / "measure", base / "measure-marker"
    subprocess.run(["git", "init", "-q", str(repo)], env=env, check=True, capture_output=True)
    hook = repo / ".git/hooks/pre-commit"
    hook.write_text(f"#!/bin/sh\n: > {shlex.quote(str(marker))}\n")
    hook.chmod(0o755)
    git = ["git", "-C", str(repo), "-c", "user.name=m", "-c", "user.email=m@example.invalid"]
    subprocess.run([*git, "config", "core.hooksPath", hooks_path], env=env, check=True)
    subprocess.run([*git, "commit", "-q", "--allow-empty", "-m", "m"], env=env, check=True, capture_output=True)
    return marker.exists()


class Doctor(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="doctor-")
        self.fx = Fixture(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def assert_refused(self, rc, out, *needles):
        self.assertEqual(rc, 1, out)
        for needle in needles:
            self.assertIn(needle, out)

    # Accepted installs, and what acceptance proves.

    def test_hooks_installed_from_the_pinned_interpreter_pass(self):
        self.fx.install(self.fx.stub_python(PIN))
        rc, out = self.fx.run()
        self.assertEqual(rc, 0, out)
        self.assertIn(f"pre-commit {PIN}'s own template", out)
        self.assertEqual(self.fx.dispatched(), [], "the doctor must not run a hook")

    def test_an_interpreter_path_with_a_space_is_read_as_pre_commit_quotes_it(self):
        self.fx.install(self.fx.stub_python(PIN, directory="tool dir/bin"))
        rc, out = self.fx.run()
        self.assertEqual(rc, 0, out)

    def test_accepted_hooks_dispatch_to_their_recorded_interpreter(self):
        stub = self.fx.stub_python(PIN, directory="tool dir/bin")
        self.fx.install(stub)
        rc, out = self.fx.run()
        self.assertEqual(rc, 0, out)
        calls = {"pre-commit": (), "pre-push": ("origin", "https://example.invalid/repo.git")}
        for hook_type, args in calls.items():
            with self.subTest(hook_type=hook_type):
                result = self.fx.run_hook(hook_type, *args)
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        records = self.fx.dispatched()
        self.assertEqual(len(records), 2, records)
        for record, (hook_type, args) in zip(records, calls.items()):
            self.assertEqual(record["via"], str(stub))
            argv = record["argv"]
            self.assertEqual(argv[:4], ["hook-impl", CONFIG_ARG, f"--hook-type={hook_type}", "--hook-dir"])
            self.assertEqual(Path(argv[4]).resolve(), self.fx.hooks.resolve())
            self.assertEqual(argv[5:], ["--", *args])

    # Refusals.

    def test_a_removed_install_python_is_refused_as_a_path_fallback(self):
        self.fx.install(self.fx.base / "gone/bin/python")
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "INSTALL_PYTHON", "falls back to whatever pre-commit is on PATH")

    def test_a_relative_install_python_is_refused_wherever_the_doctor_runs(self):
        # The installer records sys.executable, which is absolute. git starts the hook from the
        # repository root, so a relative path that resolves from the doctor's own cwd proves
        # nothing (review finding H6-RELATIVE-INSTALL-PYTHON-1).
        self.fx.stub_python(PIN)  # base/bin/python exists; repo/bin/python does not
        self.fx.install("bin/python")
        for cwd in (self.fx.base, self.fx.repo):
            with self.subTest(cwd=cwd.name):
                rc, out = self.fx.run(cwd=cwd)
                self.assert_refused(rc, out, "pre-push: INSTALL_PYTHON bin/python is not an absolute path")
        # The witness: run from the repository root, as git runs it, this hook reaches no interpreter.
        result = self.fx.run_hook("pre-push", "origin", "https://example.invalid/repo.git")
        self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(self.fx.dispatched(), [])

    def test_another_version_than_the_ci_pin_is_refused(self):
        self.fx.install(self.fx.stub_python("4.6.0"))
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "pre-commit 4.6.0", f"CI pins {PIN}")

    def test_a_missing_pre_push_hook_is_refused(self):
        self.fx.write_hook("pre-commit", self.fx.stub_python(PIN))
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "pre-push: not installed")

    def test_a_hand_written_hook_is_refused(self):
        self.fx.install(self.fx.stub_python(PIN))
        (self.fx.hooks / "pre-push").write_text("#!/bin/sh\nexec pre-commit hook-impl --hook-type=pre-push\n")
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "pre-push: not generated by pre-commit")

    def test_a_non_executable_hook_is_refused_because_git_skips_it(self):
        self.fx.install(self.fx.stub_python(PIN))
        (self.fx.hooks / "pre-push").chmod(0o644)
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "pre-push: not executable")

    def test_an_empty_install_python_is_refused_as_unreadable(self):
        # pre-commit's own untemplated hook-tmpl carries INSTALL_PYTHON=''.
        self.fx.install(self.fx.stub_python(PIN))
        self.fx.write_hook("pre-push", "")
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "pre-push: cannot read INSTALL_PYTHON")

    def test_a_marked_hook_without_the_templated_block_is_refused(self):
        self.fx.install(self.fx.stub_python(PIN))
        (self.fx.hooks / "pre-push").write_text("#!/usr/bin/env bash\n" + MARKER + "exec pre-commit\n")
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "pre-push: the templated block does not have the form pre-commit writes")

    def test_extra_lines_in_the_templated_block_are_refused(self):
        # The installer writes exactly four lines; anything more can stop or redirect dispatch.
        stub = self.fx.stub_python(PIN)
        cases = {
            "an exit": "exit 0\n",
            "an ARGS reassignment": "ARGS+=(--hook-type=pre-commit)\n",
            "an INSTALL_PYTHON reassignment": "INSTALL_PYTHON=/usr/bin/true\n",
            "a blank line": "\n",
        }
        for name, extra in cases.items():
            with self.subTest(name):
                self.fx.install(stub)
                hook = self.fx.hooks / "pre-push"
                hook.write_text(hook.read_text().replace("# end templated\n", extra + "# end templated\n", 1))
                rc, out = self.fx.run()
                self.assert_refused(rc, out, "pre-push: the templated block does not have the form pre-commit writes")

    def test_a_second_templated_block_is_refused(self):
        # The template compare removes every templated block, so a second one is invisible to it,
        # yet the hook runs it. Only the exact four-line block check sees it.
        self.fx.install(self.fx.stub_python(PIN))
        hook = self.fx.hooks / "pre-push"
        second = "# start templated\nexit 0\n# end templated\n"
        hook.write_text(hook.read_text().replace('HERE="$(cd', second + 'HERE="$(cd', 1))
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "pre-push: the templated block does not have the form pre-commit writes")

    def test_control_an_exit_in_the_block_really_stops_dispatch(self):
        # Why the case above matters: this hook runs, exits 0, and reaches no pre-commit at all.
        self.fx.install(self.fx.stub_python(PIN))
        hook = self.fx.hooks / "pre-push"
        hook.write_text(hook.read_text().replace("# end templated\n", "exit 0\n# end templated\n", 1))
        result = self.fx.run_hook("pre-push", "origin", "https://example.invalid/repo.git")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(self.fx.dispatched(), [])

    def test_a_command_after_install_python_on_its_line_is_refused(self):
        # shlex.quote writes a bare path only from its safe characters; `;` is not one of them.
        stub = self.fx.stub_python(PIN)
        self.fx.install(stub)
        hook = self.fx.hooks / "pre-push"
        line = "INSTALL_PYTHON=" + shlex.quote(str(stub)) + "\n"
        self.assertIn(line, hook.read_text(), "fixture: the stub path must be written bare")
        hook.write_text(hook.read_text().replace(line, line.rstrip("\n") + ";exit 0\n", 1))
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "pre-push: cannot read INSTALL_PYTHON")

    def test_an_empty_core_hooks_path_is_judged_as_git_runs_it(self):
        # pre-commit treats an empty core.hooksPath as unset and installs anyway. Measured on
        # git 2.50.1, git then looks in "./" and skips .git/hooks. The doctor must agree with
        # what git does here, measured with a real commit, not with what pre-commit assumes.
        self.fx.install(self.fx.stub_python(PIN))
        self.fx.git("config", "core.hooksPath", "")
        runs = git_runs_common_hooks_with(self.fx.env, self.fx.base, "")
        rc, out = self.fx.run()
        if runs:
            self.assertEqual(rc, 0, out)
        else:
            self.assert_refused(rc, out, "core.hooksPath is set")

    def test_arguments_other_than_the_installer_writes_are_refused(self):
        stub = self.fx.stub_python(PIN)
        cases = {
            "another hook type": ["hook-impl", CONFIG_ARG, "--hook-type=pre-commit"],
            "another config": ["hook-impl", "--config=unused.yaml", "--hook-type=pre-push"],
            "skip on missing config": ["hook-impl", CONFIG_ARG, "--hook-type=pre-push", "--skip-on-missing-config"],
        }
        for name, args in cases.items():
            with self.subTest(name):
                self.fx.install(stub)
                self.fx.write_hook("pre-push", stub, args=args)
                rc, out = self.fx.run()
                self.assert_refused(rc, out, "pre-push: ARGS is not exactly")

    def test_a_replaced_hook_tail_is_refused(self):
        self.fx.install(self.fx.stub_python(PIN))
        hook = self.fx.hooks / "pre-push"
        text = hook.read_text()
        hook.write_text(text[: text.index('HERE="$(cd')] + "exit 0\n")
        rc, out = self.fx.run()
        self.assert_refused(rc, out, f"pre-push: differs from pre-commit {PIN}'s own hook template")

    def test_the_template_comes_from_the_recorded_interpreter(self):
        # The same hook bytes, judged against a tool whose template differs: refused. So the
        # doctor compares with what INSTALL_PYTHON ships, not with a copy of its own.
        other = RESOURCE_TEMPLATE.replace("    exit 1\n", "    exit 2\n")
        self.fx.install(self.fx.stub_python(PIN, template=other))
        rc, out = self.fx.run()
        self.assert_refused(rc, out, f"pre-push: differs from pre-commit {PIN}'s own hook template")

    def test_core_hooks_path_is_refused_because_git_then_skips_these_hooks(self):
        self.fx.install(self.fx.stub_python(PIN))
        self.fx.git("config", "core.hooksPath", ".githooks")
        rc, out = self.fx.run()
        self.assert_refused(rc, out, "core.hooksPath is set")

    def test_arguments_are_refused(self):
        rc, out = self.fx.run("--fix")
        self.assertEqual(rc, 2, out)

    def test_the_doctor_writes_nothing(self):
        self.fx.install(self.fx.base / "gone/bin/python")
        before = self.fx.snapshot()
        self.fx.run()
        self.fx.install(self.fx.stub_python(PIN))
        middle = self.fx.snapshot()
        self.fx.run()
        self.assertEqual(middle, self.fx.snapshot())
        self.assertNotEqual(before, middle, "control: rewriting the hooks must change the snapshot")


if __name__ == "__main__":
    unittest.main()
